    def test_item_3_course_code_sanitization(self):
        """Item 3: Course code must not include title (strictly EE 211)."""
        bp = get_blank_blueprint("EE 211 - Electrical Circuits 1", "")
        self.assertEqual(bp.metadata.course_code, "EE 211")
        self.assertEqual(bp.metadata.course_title, "Electrical Circuits 1")

        bp2 = get_blank_blueprint("CE 312 – Structural Theory", "")
        self.assertEqual(bp2.metadata.course_code, "CE 312")
        self.assertEqual(bp2.metadata.course_title, "Structural Theory")

    def test_item_5_program_nomenclature(self):
        """Item 5: Bachelor of Science in ... instead of Department of ..."""
        colleges = catalog_data.COLLEGE_DEPARTMENT_CATALOG
        eng = next((c for c in colleges if "ENGINEERING" in c.get("college", "")), colleges[0])
        depts = eng.get("departments", [])
        for d in depts:
            dept_name = d.get("department", "")
            self.assertTrue(dept_name.startswith("Bachelor of Science in "), f"Expected BS in, got: {dept_name}")

    def test_item_6_catalog_year_level_and_prereqs(self):
        """Item 6: Catalog entries include year_level and prereqs."""
        colleges = catalog_data.COLLEGE_DEPARTMENT_CATALOG
        for c in colleges:
            for d in c.get("departments", []):
                for course in d.get("courses", []):
                    self.assertIn("year_level", course, f"Missing year_level in {course.get('code')}")
                    self.assertIn(course["year_level"], ["First Year", "Second Year", "Third Year", "Fourth Year"])

    def test_item_8_class_policies_autogenerated(self):
        """Item 8: Policies table auto-generates on subject creation."""
        meta = models.CourseMetadata()
        self.assertGreaterEqual(len(meta.policies_table), 5)
        self.assertTrue(any("Attendance" in p["title"] for p in meta.policies_table))

    def test_item_12_learning_plan_not_autogenerated(self):
        """Item 12: Part IX table does not autogenerate dummy topics."""
        cat_data = {"code": "EE 311", "title": "Electromagnetics", "topics": ["Coulomb's Law", "Gauss's Law"]}
        doc = courses_store.create_course("faculty_tano", "EE 311", "Electromagnetics", from_catalog=True, catalog_course_data=cat_data)
        bp_dict = doc.get("blueprint", {})
        lp = bp_dict.get("metadata", {}).get("learning_plan_table", [])
        self.assertEqual(len(lp), 0, "Part IX learning plan should not autogenerate dummy content")
        # Clean up created test file
        courses_store.delete_course("faculty_tano", doc["id"])

